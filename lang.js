  var KL = "scrapcall_collector_lang", KV = "scrapcall_collector_voice";
  function load(k, d) { try { var v = localStorage.getItem(k); return v ? JSON.parse(v) : d; } catch (e) { return d; } }
  function save(k, v) { try { localStorage.setItem(k, JSON.stringify(v)); } catch (e) {} }
  var lang = LANGS[load(KL, "")] ? load(KL, "") : "", voice = load(KV, true) !== false;

  function t(key, vars) {
    var row = W[key];
    var s = row ? (row[(LANGS[lang] || LANGS.en).i] || row[0]) : key;
    if (vars) for (var k in vars) s = s.split("{" + k + "}").join(vars[k]);
    return s;
  }
  // a voice for the language if the phone has one; without it the phone still tries with the language code
  function pick(code) {
    var vs = (w.speechSynthesis && w.speechSynthesis.getVoices()) || [], c = code.toLowerCase(), b = c.slice(0, 2), i;
    for (i = 0; i < vs.length; i++) if (String(vs[i].lang).toLowerCase().replace("_", "-") === c) return vs[i];
    for (i = 0; i < vs.length; i++) if (String(vs[i].lang).toLowerCase().indexOf(b) === 0) return vs[i];
    return null;
  }
  function speak(text, force) {
    if ((!voice && !force) || !w.speechSynthesis || !text) return;
    try {
      var s = w.speechSynthesis; s.cancel();
      var L = LANGS[lang] || LANGS.en, u = new w.SpeechSynthesisUtterance(String(text).replace(/[·—]/g, ","));
      u.lang = L.tts; var v = pick(L.tts); if (v) u.voice = v; u.rate = 0.9;
      s.speak(u);
    } catch (e) {}
  }
  if (w.speechSynthesis && w.speechSynthesis.getVoices) { try { w.speechSynthesis.getVoices(); } catch (e) {} }

